          FROM DEPOSIT_ITEM B
          JOIN INSTANT_PAYMENT E
            ON B.EVENT_PAYMENT_ID = E.EVENT_PAYMENT_ID
          JOIN INSTANT_PAYMENT P
            ON E.PAYMENT_iD = P.REVERSED_PAYMENT_iD
        
         WHERE P.REVERSE_E_INVOICE_NBR = :E_INVOICE_NBR
        
