        JOIN CRM.GM_MODEL H ON H.MODEL_ID = E.MODEL_ID
        JOIN CRM.GM_BRAND BR ON H.BRAND_ID=BR.BRAND_ID 
        AND BR.BRAND_CODE<>'Others'
        JOIN CRM.AGREEMENT_ORDER M ON D.ORDER_ITEM_ID = M.ORDER_ITEM_ID
        JOIN AGREEMENT AG ON M.AGREEMENT_ID = AG.AGREEMENT_ID
        AND AG.AGREEMENT_TYPE_ID='4'
        LEFT JOIN CRM.GOODS_ORDER_ATTR I ON E.GOODS_ORDER_ID = I.GOODS_ORDER_ID 
        AND I.ATTR_ID = 2725 
    WHERE 
        B.BILLING_CYCLE_ID IS NOT NULL
        AND Z.REVERSE_E_INVOICE_NBR = :E_INVOICE_NBR

        AND D.SUBS_EVENT_ID = 1
    ) M ON M.CUST_ORDER_ID = B.CUST_ORDER_ID
    AND M.ACC_NBR=B.ACC_nBR 

    UNION
    --tax
    SELECT 
        P.CUST_ORDER_ID,
        P.ACC_NBR,
        P.ACCT_ID,
        P.CHARGE AS CHARGE,
        P.FEE_ITEM,
        P.PAYMENT_TIME,
        P.PAYMENT_DATE,
        P.TAX_CHARGE AS TAX_CHARGE,
        P.ROUNDING_AMOUNT,
        P.TAX_RATE,
        P.OFFER_NAME,
        M.GOODS_ORDER_ID,
        CASE 
            WHEN M.MODEL_NAME IS NOT NULL 
            THEN M.MODEL_NAME
            ELSE NULL
        END AS MODEL_NAME

from


    ( SELECT 
        D.CUST_ORDER_ID,
        D.ACC_NBR,
        D.ACCT_ID,
        B.CHARGE AS CHARGE,
        F.ACCT_ITEM_TYPE_NAME AS FEE_ITEM,
        TO_CHAR(B.State_Date, 'HH:MIam') AS PAYMENT_TIME,
        TO_CHAR(B.State_Date, 'DD-Mon-YYYY') AS PAYMENT_DATE,
        0 AS TAX_CHARGE,
        0 AS ROUNDING_AMOUNT,
        J.TAX_RATE,
        AG.AGREEMENT_SHORT_NAME AS OFFER_NAME
    FROM  EVENT_CHARGE B, RE_SUBS_ORDER_INST C, CRM.ORDER_ITEM D, ACCT_ITEM_TYPE F,GST_TYPE H,GST_TYPE_TAX_RATE J,OFFER K,CRM.AGREEMENT_ORDER M,AGREEMENT AG,EVENT_CHARGE Z
    WHERE  B.EVENT_INST_ID = C.EVENT_INST_ID
    AND D.ORDER_ITEM_ID = C.ORDER_ITEM_ID
    AND F.GST_TYPE = H.GST_TYPE
    AND B.EVENT_INST_ID=Z.REVERSED_INST_iD
    AND Z.PRICE_ID=B.PRICE_ID
    AND Z.ACCT_ITEM_TYPE_ID=B.ACCT_ITEM_TYPE_ID
    AND D.SUBS_PLAN_ID=K.OFFER_ID
    AND D.SUBS_EVENT_ID=1
    AND D.CUST_ORDER_ID = C.CUST_ORDER_ID
    AND F.ACCT_ITEM_TYPE_ID = B.ACCT_ITEM_TYPE_ID
    AND B.BILLING_CYCLE_ID IS NOT NULL
    AND Z.REVERSE_E_INVOICE_NBR = :E_INVOICE_NBR
    AND H.GST_TYPE = 'Z'
    AND D.ORDER_ITEM_ID=M.ORDER_ITEM_ID
    AND M.AGREEMENT_ID = AG.AGREEMENT_ID
    AND H.GST_TYPE=J.GST_TYPE
    AND F.ACCT_ITEM_TYPE_CODE not in ('ZRL','ROUNDING')
    ) P
    LEFT JOIN (
    ---- GOODS Info
    SELECT  
     DISTINCT 
        D.CUST_ORDER_ID,
        E.GOODS_ORDER_ID,
        D.ACC_NBR,
        CASE 
            WHEN I.VALUE IS NOT NULL 
            THEN H.MODEL_NAME || ',' || I.VALUE  
            ELSE H.MODEL_NAME                  
        END AS MODEL_NAME
    FROM 
         EVENT_CHARGE B
        JOIN RE_SUBS_ORDER_INST C ON B.EVENT_INST_ID = C.EVENT_INST_ID
        JOIN EVENT_CHARGE Z ON  B.EVENT_INST_ID=Z.REVERSED_INST_iD AND Z.PRICE_ID=B.PRICE_ID AND Z.ACCT_ITEM_TYPE_ID=B.ACCT_ITEM_TYPE_ID

        JOIN CRM.ORDER_ITEM D ON D.ORDER_ITEM_ID = C.ORDER_ITEM_ID AND D.CUST_ORDER_ID = C.CUST_ORDER_ID
        JOIN ACCT_ITEM_TYPE F ON F.ACCT_ITEM_TYPE_ID = B.ACCT_ITEM_TYPE_ID
        JOIN CRM.GOODS_ORDER E ON D.ORDER_ITEM_ID = E.ORDER_ITEM_ID
        JOIN CRM.GM_MODEL H ON H.MODEL_ID = E.MODEL_ID
        JOIN CRM.GM_BRAND BR ON H.BRAND_ID=BR.BRAND_ID 
        JOIN CRM.AGREEMENT_ORDER M ON D.ORDER_ITEM_ID = M.ORDER_ITEM_ID
        JOIN AGREEMENT AG ON M.AGREEMENT_ID = AG.AGREEMENT_ID
        AND AG.AGREEMENT_TYPE_ID='4'
        AND BR.BRAND_CODE<>'Others'
        LEFT JOIN CRM.GOODS_ORDER_ATTR I ON E.GOODS_ORDER_ID = I.GOODS_ORDER_ID 
        AND I.ATTR_ID = 2725 
    WHERE 
        B.BILLING_CYCLE_ID IS NOT NULL
        AND D.SUBS_EVENT_ID = 1
    ) M ON M.CUST_ORDER_ID = P.CUST_ORDER_ID
    AND M.ACC_NBR=P.ACC_nBR
    
    UNION
      SELECT 
        D.CUST_ORDER_ID,
        D.ACC_NBR,
        D.ACCT_ID,
        A.CHARGE,
        E.ACCT_ITEM_TYPE_NAME AS FEE_ITEM,
        TO_CHAR(A.State_Date, 'HH:MIam') AS PAYMENT_TIME,
        TO_CHAR(A.State_Date, 'DD-Mon-YYYY') AS PAYMENT_DATE,
        0 AS TAX_CHARGE,
        0 AS ROUNDING_AMOUNT,
        0 AS TAX_RATE,
        AG.AGREEMENT_SHORT_NAME AS OFFER_NAME,
        NULL AS MODEL_NAME,  
        NULL AS GOODS_ORDER_ID
    FROM deposit_charge A
    JOIN RE_SUBS_ORDER_INST B ON A.event_inst_id = B.event_inst_id
    JOIN event_payment C ON B.event_payment_Id = C.event_payment_Id
    JOIN CRM.ORDER_ITEM D ON B.ORDER_ITEM_ID = D.ORDER_ITEM_ID
    JOIN ACCT_ITEM_TYPE E ON A.ACCT_ITEM_TYPE_ID = E.ACCT_ITEM_TYPE_ID
    JOIN CRM.AGREEMENT_ORDER M ON D.ORDER_ITEM_ID = M.ORDER_ITEM_ID
    JOIN AGREEMENT AG ON M.AGREEMENT_ID = AG.AGREEMENT_ID
    JOIN INSTANT_PAYMENT P ON P.EVENT_PAYMENT_ID=B.EVENT_PAYMENT_ID
    JOIN INSTANT_PAYMENT IP ON IP.REVERSED_PAYMENT_ID=P.PAYMENT_ID
    WHERE  IP.REVERSE_E_INVOICE_NBR = :E_INVOICE_NBR
    AND A.CHARGE>0
      AND D.SUBS_EVENT_ID = 1
    
     )T
   ORDER BY T.CUST_ORDER_ID, T.ACC_NBR, T.CHARGE

