-- ===== 10250 SALE_INVOICE_PAYMENT_SUMMARY_INFO =====
SELECT 
    NVL(MAIN_FEE.TOTAL_AMOUNT, 0) + NVL(DEPOSIT_FEE.DEPOSIT_AMOUNT, 0) AS TOTAL_AMOUNT
FROM 
    (-- 主费用部分
    SELECT SUM(B.CHARGE) AS TOTAL_AMOUNT
    FROM EVENT_CHARGE B
    JOIN ACCT_ITEM_TYPE C ON B.ACCT_ITEM_TYPE_ID = C.ACCT_ITEM_TYPE_ID
    WHERE C.ACCT_ITEM_TYPE_CODE NOT IN ('ZRL','ROUNDING')
      AND B.BILLING_CYCLE_ID IS NOT NULL
      AND B.E_INVOICE_NBR = :E_INVOICE_NBR
    ) MAIN_FEE,
    (-- 押金部分（转换为相同单位）
    SELECT SUM(A.CHARGE)  * -1 AS DEPOSIT_AMOUNT
    FROM DEPOSIT_ITEM A 
    JOIN EVENT_PAYMENT B 
      ON A.ACCT_ID = B.ACCT_ID 
     AND A.EVENT_PAYMENT_ID = B.EVENT_PAYMENT_ID
    JOIN INSTANT_PAYMENT C 
      ON C.EVENT_PAYMENT_ID = B.EVENT_PAYMENT_ID
    WHERE C.E_INVOICE_NBR = :E_INVOICE_NBR
    ) DEPOSIT_FEE

